// Input codes. Presets name keys by libuiohook's key codes (what input-overlay sends over its websocket), mouse
// buttons by uiohook's 1–5, and gamepad buttons and axes by SDL's numbering. The browser speaks KeyboardEvent.code,
// MouseEvent.button and the standard Gamepad layout, so these tables turn the browser's into theirs.
(() => {
  const KEYS = {
    Escape: 0x01, Digit1: 0x02, Digit2: 0x03, Digit3: 0x04, Digit4: 0x05, Digit5: 0x06, Digit6: 0x07, Digit7: 0x08,
    Digit8: 0x09, Digit9: 0x0a, Digit0: 0x0b, Minus: 0x0c, Equal: 0x0d, Backspace: 0x0e, Tab: 0x0f,
    KeyQ: 0x10, KeyW: 0x11, KeyE: 0x12, KeyR: 0x13, KeyT: 0x14, KeyY: 0x15, KeyU: 0x16, KeyI: 0x17, KeyO: 0x18, KeyP: 0x19,
    BracketLeft: 0x1a, BracketRight: 0x1b, Enter: 0x1c, ControlLeft: 0x1d,
    KeyA: 0x1e, KeyS: 0x1f, KeyD: 0x20, KeyF: 0x21, KeyG: 0x22, KeyH: 0x23, KeyJ: 0x24, KeyK: 0x25, KeyL: 0x26,
    Semicolon: 0x27, Quote: 0x28, Backquote: 0x29, ShiftLeft: 0x2a, Backslash: 0x2b,
    KeyZ: 0x2c, KeyX: 0x2d, KeyC: 0x2e, KeyV: 0x2f, KeyB: 0x30, KeyN: 0x31, KeyM: 0x32,
    Comma: 0x33, Period: 0x34, Slash: 0x35, ShiftRight: 0x36, NumpadMultiply: 0x37, AltLeft: 0x38, Space: 0x39,
    CapsLock: 0x3a, F1: 0x3b, F2: 0x3c, F3: 0x3d, F4: 0x3e, F5: 0x3f, F6: 0x40, F7: 0x41, F8: 0x42, F9: 0x43, F10: 0x44,
    NumLock: 0x45, ScrollLock: 0x46, Numpad7: 0x47, Numpad8: 0x48, Numpad9: 0x49, NumpadSubtract: 0x4a,
    Numpad4: 0x4b, Numpad5: 0x4c, Numpad6: 0x4d, NumpadAdd: 0x4e, Numpad1: 0x4f, Numpad2: 0x50, Numpad3: 0x51,
    Numpad0: 0x52, NumpadDecimal: 0x53, IntlBackslash: 0x56, F11: 0x57, F12: 0x58,
    NumpadEnter: 0x0e1c, ControlRight: 0x0e1d, NumpadDivide: 0x0e35, PrintScreen: 0x0e37, AltRight: 0x0e38,
    Pause: 0x0e45, Home: 0x0e47, PageUp: 0x0e49, End: 0x0e4f, PageDown: 0x0e51, Insert: 0x0e52, Delete: 0x0e53,
    MetaLeft: 0x0e5b, MetaRight: 0x0e5c, ContextMenu: 0x0e5d,
    ArrowUp: 0xe048, ArrowLeft: 0xe04b, ArrowRight: 0xe04d, ArrowDown: 0xe050,
  };
  // names for the key history (uiohook code → label)
  const NAMES = {};
  for (const [code, vc] of Object.entries(KEYS)) {
    NAMES[vc] = code.replace(/^Key|^Digit/, '').replace(/Left$|Right$/, '')
      .replace('Control', 'Ctrl').replace('Escape', 'Esc').replace('Meta', 'Win').replace('Arrow', '')
      .replace('Backspace', '⌫').replace('Enter', '⏎').replace('Space', 'Space').replace('Numpad', 'Num ');
  }
  Object.assign(NAMES, { 0x0c: '-', 0x0d: '=', 0x1a: '[', 0x1b: ']', 0x27: ';', 0x28: "'", 0x29: '`', 0x2b: '\\', 0x33: ',', 0x34: '.', 0x35: '/', 0xe048: '↑', 0xe04b: '←', 0xe04d: '→', 0xe050: '↓' });
  const MODIFIERS = new Set([0x1d, 0x0e1d, 0x2a, 0x36, 0x38, 0x0e38, 0x0e5b, 0x0e5c]);

  // Windows virtual-key code (input-overlay's "rawcode" on Windows) → the same uiohook code as above. input-overlay
  // 5.1 changed its own key codes (its A is 5.0's B), but the Windows code is the same in both, so it's read first.
  const VK = {
    0x1b: 0x01, 0x09: 0x0f, 0x14: 0x3a, 0x20: 0x39, 0x0d: 0x1c, 0x08: 0x0e,
    0xa0: 0x2a, 0xa1: 0x36, 0x10: 0x2a, 0xa2: 0x1d, 0xa3: 0x0e1d, 0x11: 0x1d, 0xa4: 0x38, 0xa5: 0x0e38, 0x12: 0x38,
    0x5b: 0x0e5b, 0x5c: 0x0e5c, 0x5d: 0x0e5d, 0x2c: 0x0e37, 0x91: 0x46, 0x13: 0x0e45, 0x90: 0x45,
    0x25: 0xe04b, 0x26: 0xe048, 0x27: 0xe04d, 0x28: 0xe050, 0x2d: 0x0e52, 0x2e: 0x0e53, 0x24: 0x0e47, 0x23: 0x0e4f, 0x21: 0x0e49, 0x22: 0x0e51,
    0x6a: 0x37, 0x6b: 0x4e, 0x6d: 0x4a, 0x6e: 0x53, 0x6f: 0x0e35,
    0xba: 0x27, 0xbb: 0x0d, 0xbc: 0x33, 0xbd: 0x0c, 0xbe: 0x34, 0xbf: 0x35, 0xc0: 0x29, 0xdb: 0x1a, 0xdc: 0x2b, 0xdd: 0x1b, 0xde: 0x28, 0xe2: 0x56,
  };
  'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('').forEach((c) => (VK[c.charCodeAt(0)] = KEYS['Key' + c]));
  '0123456789'.split('').forEach((d) => (VK[d.charCodeAt(0)] = KEYS['Digit' + d]));
  for (let i = 0; i < 12; i++) VK[0x70 + i] = KEYS['F' + (i + 1)];
  for (let i = 0; i < 10; i++) VK[0x60 + i] = KEYS['Numpad' + i];

  // MouseEvent.button → uiohook (left 1, right 2, middle 3, back 4, forward 5)
  const MOUSE = { 0: 1, 1: 3, 2: 2, 3: 4, 4: 5 };

  // standard Gamepad button index → SDL button (south, east, west, north, back, guide, start, sticks, shoulders, d-pad)
  const PAD = { 0: 0, 1: 1, 2: 2, 3: 3, 4: 9, 5: 10, 8: 4, 9: 6, 10: 7, 11: 8, 12: 11, 13: 12, 14: 13, 15: 14, 16: 5, 17: 20 };
  // SDL axes: 0 left x, 1 left y, 2 right x, 3 right y, 4 left trigger, 5 right trigger
  const SDL = { DPAD_UP: 11, DPAD_DOWN: 12, DPAD_LEFT: 13, DPAD_RIGHT: 14, LEFT_STICK: 7, RIGHT_STICK: 8, GUIDE: 5 };

  window.IOCodes = { KEYS, VK, NAMES, MODIFIERS, MOUSE, PAD, SDL };
})();
